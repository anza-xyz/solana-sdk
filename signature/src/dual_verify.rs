//! Opt-in shadow verification for evaluating SIMD-0376 on live traffic.
//!
//! With the `dual-verify` feature enabled and an observer registered through
//! [`set_observer`], every [`Signature::verify`] call runs both
//! `verify_dalek` (whose result is returned, as without this feature) and
//! `verify_simd0376`, times each, and passes a [`DualVerifyEvent`] to the
//! observer. Without an observer, `verify` runs `verify_dalek` alone.
//!
//! This module does no I/O: the observer decides what to record. It runs on
//! the verifying thread, so it should be cheap.

pub use solana_ed25519::ed_sigs::Error as VerifyError;
use {
    crate::Signature,
    core::cell::Cell,
    solana_ed25519::ed_sigs::{Signature as EdSignature, VerificationKey},
    std::{sync::OnceLock, time::Instant},
};

/// Results and timings of both verification rules for one signature.
#[derive(Debug)]
pub struct DualVerifyEvent<'a> {
    pub pubkey: &'a [u8],
    pub signature: &'a Signature,
    pub message: &'a [u8],
    /// Which rule ran first. Alternates per call on each thread so cache
    /// warm-up does not favour either rule.
    pub dalek_first: bool,
    /// Public-key decompression, shared by both rules and not included in
    /// either rule's time.
    pub decompress_ns: u32,
    pub dalek: Result<(), VerifyError>,
    pub dalek_ns: u32,
    pub simd0376: Result<(), VerifyError>,
    pub simd0376_ns: u32,
}

/// Receives one [`DualVerifyEvent`] per verified signature.
pub type Observer = fn(&DualVerifyEvent<'_>);

static OBSERVER: OnceLock<Observer> = OnceLock::new();

std::thread_local! {
    static CALLS: Cell<u64> = const { Cell::new(0) };
}

/// Registers the process-wide observer. Can be set once; returns the given
/// observer back if one is already registered.
pub fn set_observer(observer: Observer) -> Result<(), Observer> {
    OBSERVER.set(observer)
}

fn elapsed_ns(start: Instant) -> u32 {
    u32::try_from(start.elapsed().as_nanos()).unwrap_or(u32::MAX)
}

/// Returns the `verify_dalek` result. With an observer registered, also runs
/// `verify_simd0376` and reports both.
pub(crate) fn verify(
    signature: &Signature,
    pubkey_bytes: &[u8],
    message_bytes: &[u8],
) -> Result<(), VerifyError> {
    let ed_sig = EdSignature::from(*signature.as_array());
    let Some(observer) = OBSERVER.get() else {
        return VerificationKey::try_from(pubkey_bytes)?.verify_dalek(&ed_sig, message_bytes);
    };

    let start = Instant::now();
    let publickey = VerificationKey::try_from(pubkey_bytes);
    let decompress_ns = elapsed_ns(start);

    let dalek_first = CALLS.with(|calls| {
        let n = calls.get();
        calls.set(n.wrapping_add(1));
        n % 2 == 0
    });
    let (dalek, dalek_ns, simd0376, simd0376_ns) = match &publickey {
        Err(err) => (Err(*err), 0, Err(*err), 0),
        Ok(vk) => {
            let run_dalek = || {
                let start = Instant::now();
                let result = vk.verify_dalek(&ed_sig, message_bytes);
                (result, elapsed_ns(start))
            };
            let run_simd0376 = || {
                let start = Instant::now();
                let result = vk.verify_simd0376(&ed_sig, message_bytes);
                (result, elapsed_ns(start))
            };
            if dalek_first {
                let (d, dn) = run_dalek();
                let (s, sn) = run_simd0376();
                (d, dn, s, sn)
            } else {
                let (s, sn) = run_simd0376();
                let (d, dn) = run_dalek();
                (d, dn, s, sn)
            }
        }
    };

    observer(&DualVerifyEvent {
        pubkey: pubkey_bytes,
        signature,
        message: message_bytes,
        dalek_first,
        decompress_ns,
        dalek,
        dalek_ns,
        simd0376,
        simd0376_ns,
    });
    dalek
}

#[cfg(test)]
mod tests {
    use {
        super::*,
        std::{sync::Mutex, vec::Vec},
    };

    /// Accepted by `verify_simd0376` (cofactored) but rejected by
    /// `verify_dalek` (cofactorless): a valid signature with an order-8 point
    /// added to `R`. Generated by ed25519-dual-verify in anza-xyz/cryptography.
    const TORSION_PUBKEY: &str = "c8f4cfd7ec9c81e16c77144a4d1ce0dca0339661df313cceb9203113468fb608";
    const TORSION_SIG: &str = "9e556c89c2f8fdce92210fa586de4cf4cf17eacf4bb3060ca88c0011e90979c7\
                               d27eaa759f0bdf95f46276422e6d45a90f46c4fe307cd54bf7f926016bce630b";
    const TORSION_MSG: &[u8] = b"dual verify";

    fn unhex(s: &str) -> Vec<u8> {
        s.as_bytes()
            .chunks(2)
            .map(|c| u8::from_str_radix(core::str::from_utf8(c).unwrap(), 16).unwrap())
            .collect()
    }

    type Seen = (Vec<u8>, bool, bool, bool);
    static SEEN: Mutex<Vec<Seen>> = Mutex::new(Vec::new());

    fn record(event: &DualVerifyEvent<'_>) {
        // The observer is process-wide: ignore other tests' verifications.
        if event.message != TORSION_MSG {
            return;
        }
        SEEN.lock().unwrap().push((
            event.signature.as_array().to_vec(),
            event.dalek.is_ok(),
            event.simd0376.is_ok(),
            event.dalek_first,
        ));
    }

    #[test]
    fn test_observer_sees_both_results_and_dalek_decides() {
        let pubkey = unhex(TORSION_PUBKEY);
        let signature = Signature::try_from(unhex(TORSION_SIG).as_slice()).unwrap();

        // No observer yet: dalek alone.
        assert!(!signature.verify(&pubkey, TORSION_MSG));
        assert!(SEEN.lock().unwrap().is_empty());

        assert!(set_observer(record).is_ok());
        assert!(set_observer(record).is_err());

        // dalek rejects, so verify rejects, but the observer sees simd0376 accept.
        assert!(!signature.verify(&pubkey, TORSION_MSG));
        // Second call runs the rules in the other order.
        assert!(!signature.verify(&pubkey, TORSION_MSG));
        // Malformed public key: both rejected, still reported.
        assert!(!signature.verify(&[2u8; 32], TORSION_MSG));

        let seen = SEEN.lock().unwrap();
        assert_eq!(seen.len(), 3);
        assert_eq!(
            seen[0],
            (signature.as_array().to_vec(), false, true, seen[0].3)
        );
        assert_ne!(seen[0].3, seen[1].3);
        assert_eq!((seen[2].1, seen[2].2), (false, false));
    }
}
